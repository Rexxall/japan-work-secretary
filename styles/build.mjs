// Builds styles.css from the shared UI kit (scoped to this plugin) and the plugin's own rules.
import { readFileSync, writeFileSync } from 'fs';

const ROOT = ':is(.japan-work-dashboard, .jws-modal, .jws-settings)';
const kit = readFileSync('styles/kit.css', 'utf8').replaceAll('__R__', ROOT);
const own = readFileSync('styles/plugin.css', 'utf8');
writeFileSync('styles.css', `/* Generated by styles/build.mjs. Edit styles/kit.css or styles/plugin.css. */\n\n${kit}\n${own}`);
